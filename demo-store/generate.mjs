#!/usr/bin/env node
/**
 * Generates the demo store's catalog pages from data/aurum/catalog.json (owner: A6, P8.2b).
 *
 *   node demo-store/generate.mjs          # writes demo-store/public/{index,p/*,c/*}.html
 *   node demo-store/generate.mjs --check  # exits 1 if the committed pages are out of date
 *
 * One product page per Aurum design (/p/<slug>, JSON-LD Product + Open Graph, images served by GiftFit's
 * /catalog), one page per category (/c/<slug>, the same slugs the old Aurum storefront used) and the
 * home page. Pages are committed, so the Docker image needs no build step and server.mjs stays tiny.
 * Hand-written pages (no GENERATED marker, e.g. the three original PDPs and about.html) are never
 * overwritten. `{{GIFTFIT_ORIGIN}}` is filled in by server.mjs at request time.
 */
import { readFileSync, existsSync, mkdirSync, writeFileSync } from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const HERE = path.dirname(fileURLToPath(import.meta.url));
export const PUBLIC_DIR = path.join(HERE, "public");
export const CATALOG_PATH = path.join(HERE, "..", "data", "aurum", "catalog.json");
export const GENERATED = "<!-- generated by demo-store/generate.mjs; edit the generator, not this file -->";
export const SNIPPET = '<script src="{{GIFTFIT_ORIGIN}}/giftfit.js" data-store="aurum" async></script>';
export const CATEGORIES = [
  { value: "earring", slug: "earrings", label: "Earrings" },
  { value: "necklace", slug: "necklaces", label: "Necklaces" },
  { value: "ring", slug: "rings", label: "Rings" },
  { value: "bracelet", slug: "bracelets", label: "Bracelets" },
  { value: "watch", slug: "watches", label: "Watches" },
];

const esc = (s) => String(s ?? "").replace(/[&<>"']/g, (c) => ({ "&": "&amp;", "<": "&lt;", ">": "&gt;", '"': "&quot;", "'": "&#39;" })[c]);
const money = (n) => `$${Number(n).toFixed(2)}`;
const img = (p) => `{{GIFTFIT_ORIGIN}}${p}`;

function layout({ title, body, head = "", lang = "en" }) {
  return `<!doctype html>
${GENERATED}
<html lang="${lang}">
  <head>
    <meta charset="utf-8" />
    <meta name="viewport" content="width=device-width, initial-scale=1" />
    <title>${esc(title)} · Lumen &amp; Co.</title>
    <link rel="stylesheet" href="/styles.css" />
${head}  </head>
  <body>
    <header><a href="/">Lumen &amp; Co.</a><nav>${CATEGORIES.map((c) => `<a href="/c/${c.slug}">${c.label}</a>`).join("")}<a href="/about">About</a></nav></header>
    <p class="banner">Fictional demo shop on its own origin. It knows nothing about GiftFit except one script tag. Products and photos come from the GiftFit Aurum demo catalog.</p>
    <main>
${body}
    </main>
    <footer>Lumen &amp; Co. is not a real store. No orders are taken.</footer>
    <script>
      ["giftfit:sent", "giftfit:close"].forEach(function (type) {
        window.addEventListener(type, function () {
          var el = document.getElementById("events");
          if (el) el.textContent += type + " ";
        });
      });
    </script>
    <!-- The only GiftFit integration on this site: -->
    ${SNIPPET}
  </body>
</html>
`;
}

/** The catalog as the shop shows it. */
export function loadProducts(catalogPath = CATALOG_PATH) {
  const raw = JSON.parse(readFileSync(catalogPath, "utf8"));
  return raw.map((s) => {
    const a = s.attributes ?? {};
    const variants = (s.variants?.length ? s.variants : [{ metal: a.metal, price: s.price, material: a.material }]).map((v) => ({ metal: v.metal, price: v.price, material: v.material ?? String(v.metal).replace(/_/g, " ") }));
    return {
      id: s.id,
      sku: a.sku,
      slug: a.slug,
      title: s.title,
      category: s.category,
      price: s.price,
      currency: s.currency,
      image: s.images?.[0] ?? a.vto_image,
      description: a.description ?? "",
      isPhoto: a.image_source === "ai_photo",
      variants,
    };
  });
}

function card(p) {
  return `        <a class="card" href="/p/${esc(p.slug)}"><img src="${img(p.image)}" alt="" loading="lazy" /><div><strong>${esc(p.title)}</strong><br />${money(p.price)}</div></a>`;
}

function productPage(p) {
  const prices = p.variants.map((v) => v.price);
  const offers =
    p.variants.length > 1
      ? { "@type": "AggregateOffer", lowPrice: Math.min(...prices).toFixed(2), highPrice: Math.max(...prices).toFixed(2), priceCurrency: p.currency, offerCount: p.variants.length, offers: [{ "@type": "Offer", price: Number(p.price).toFixed(2), priceCurrency: p.currency, availability: "https://schema.org/InStock" }] }
      : { "@type": "Offer", price: Number(p.price).toFixed(2), priceCurrency: p.currency, availability: "https://schema.org/InStock" };
  const ld = { "@context": "https://schema.org", "@type": "Product", name: p.title, sku: p.sku, image: [img(p.image)], description: p.description, brand: { "@type": "Brand", name: "Lumen & Co." }, url: `/p/${p.slug}`, offers };
  const head = `    <meta property="og:type" content="product" />
    <meta property="og:title" content="${esc(p.title)}" />
    <meta property="og:image" content="${img(p.image)}" />
    <meta property="product:price:amount" content="${Number(p.price).toFixed(2)}" />
    <meta property="product:price:currency" content="${esc(p.currency)}" />
    <script type="application/ld+json">
${JSON.stringify(ld, null, 2).replace(/</g, "\\u003c")}
    </script>
`;
  const cat = CATEGORIES.find((c) => c.value === p.category);
  const metals = p.variants.length > 1 ? `\n          <p>Also in: ${p.variants.map((v) => `${esc(v.material)} (${money(v.price)})`).join(", ")}</p>` : "";
  const body = `      <p><a href="/c/${cat?.slug ?? ""}">← ${esc(cat?.label ?? "All jewelry")}</a></p>
      <div class="pdp">
        <img src="${img(p.image)}" alt="${esc(p.title)}" />
        <div>
          <h1>${esc(p.title)}</h1>
          <p class="price">${money(p.price)}</p>
          <p>${esc(p.description)}</p>${metals}
          <form action="/cart/add" method="post" onsubmit="return false">
            <button type="submit" name="add">Add to cart</button>
          </form>
          <p id="events" data-testid="host-events" aria-live="polite"></p>
        </div>
      </div>`;
  return layout({ title: p.title, head, body });
}

function categoryPage(c, products) {
  const items = products.filter((p) => p.category === c.value);
  const body = `      <h1>${esc(c.label)}</h1>
      <p>${items.length} designs. Not sure what they'd like? Ask the gift assistant in the corner.</p>
      <div class="grid">
${items.map(card).join("\n")}
      </div>
      <p id="events" data-testid="host-events" aria-live="polite"></p>`;
  return layout({ title: c.label, body });
}

function homePage(products) {
  const featured = products.filter((p) => p.isPhoto).slice(0, 12);
  const body = `      <h1>Fine jewelry, gifted right</h1>
      <p>Not sure what they'd like? Ask the gift assistant in the corner.</p>
      <p class="cats">${CATEGORIES.map((c) => `<a href="/c/${c.slug}">${c.label} (${products.filter((p) => p.category === c.value).length})</a>`).join(" · ")}</p>
      <h2>Featured</h2>
      <div class="grid">
${featured.map(card).join("\n")}
      </div>
      <p id="events" data-testid="host-events" aria-live="polite"></p>`;
  return layout({ title: "Jewelry", body });
}

/** Every generated page: relative path → HTML. */
export function renderSite(products = loadProducts()) {
  const out = new Map();
  out.set("index.html", homePage(products));
  for (const c of CATEGORIES) out.set(`c/${c.slug}.html`, categoryPage(c, products));
  for (const p of products) out.set(`p/${p.slug}.html`, productPage(p));
  return out;
}

/** True when a file on disk is hand-written (exists and has no GENERATED marker). */
export function isHandWritten(file) {
  return existsSync(file) && !readFileSync(file, "utf8").includes(GENERATED);
}

function main() {
  const check = process.argv.includes("--check");
  const site = renderSite();
  let written = 0;
  let stale = 0;
  let kept = 0;
  for (const [rel, html] of site) {
    const file = path.join(PUBLIC_DIR, rel);
    if (isHandWritten(file)) {
      kept++;
      continue;
    }
    const current = existsSync(file) ? readFileSync(file, "utf8") : null;
    if (current === html) continue;
    if (check) {
      stale++;
      console.error(`out of date: ${rel}`);
      continue;
    }
    mkdirSync(path.dirname(file), { recursive: true });
    writeFileSync(file, html);
    written++;
  }
  console.log(`${site.size} pages (${kept} hand-written kept), ${check ? `${stale} out of date` : `${written} written`}`);
  if (check && stale) process.exit(1);
}

if (process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)) main();
