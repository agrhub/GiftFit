#!/usr/bin/env node
/**
 * Generates the demo store's catalog pages from fixtures/aurum/catalog.json (owner: A6, P8.2b).
 *
 *   node server/demo-store/generate.mjs          # writes server/demo-store/public/{index,p/*,c/*}.html
 *   node server/demo-store/generate.mjs --check  # exits 1 if the committed pages are out of date
 *
 * One product page per Aurum design (/p/<slug>, JSON-LD Product + Open Graph, images served by GiftFit's
 * /catalog), one page per category (/c/<slug>, the same slugs the old Aurum storefront used) and the
 * home page. Pages are committed, so the Docker image needs no build step and server.mjs stays tiny.
 * Hand-written pages (no GENERATED marker, e.g. the three original PDPs and about.html) are never
 * overwritten; they carry a copy of siteHeader()/siteFooter(), so update them by hand when those change.
 * `{{GIFTFIT_ORIGIN}}` is filled in by server.mjs at request time. Fonts (Playfair Display, Manrope; OFL,
 * public/fonts/OFL.txt) are self-hosted so the shop loads nothing from a third party but the GiftFit tag.
 */
import { readFileSync, existsSync, mkdirSync, writeFileSync } from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const HERE = path.dirname(fileURLToPath(import.meta.url));
export const PUBLIC_DIR = path.join(HERE, "public");
export const CATALOG_PATH = path.join(HERE, "..", "..", "fixtures", "aurum", "catalog.json");
// The marker is matched byte for byte in the committed pages, so it keeps the path from before demo-store/ moved under server/.
export const GENERATED = "<!-- generated by demo-store/generate.mjs; edit the generator, not this file -->";
export const SNIPPET = '<script src="{{GIFTFIT_ORIGIN}}/giftfit.js" data-store="aurum" async></script>';
/** `tile`: the SKU whose photo stands for the category on the home page. */
export const CATEGORIES = [
  { value: "earring", slug: "earrings", label: "Earrings", tile: "AUR-EAR-028" },
  { value: "necklace", slug: "necklaces", label: "Necklaces", tile: "AUR-NEC-021" },
  { value: "ring", slug: "rings", label: "Rings", tile: "AUR-RNG-005" },
  { value: "bracelet", slug: "bracelets", label: "Bracelets", tile: "AUR-BRC-003" },
  { value: "watch", slug: "watches", label: "Watches", tile: "AUR-WCH-002" },
];
/** The two photos in the home page hero. */
const HERO = { main: "AUR-NEC-017", accent: "AUR-EAR-038" };
const METAL_LABELS = { yellow_gold: "Yellow gold", rose_gold: "Rose gold", white_gold: "White gold", silver: "Silver", platinum: "Platinum", mixed_two_tone: "Two-tone" };

const esc = (s) => String(s ?? "").replace(/[&<>"']/g, (c) => ({ "&": "&amp;", "<": "&lt;", ">": "&gt;", '"': "&quot;", "'": "&#39;" })[c]);
const money = (n) => `$${Number(n).toLocaleString("en-US", { minimumFractionDigits: 2, maximumFractionDigits: 2 })}`;
const img = (p) => `{{GIFTFIT_ORIGIN}}${p}`;
const catOf = (p) => CATEGORIES.find((c) => c.value === p.category);
/** Photos fill their frame; the transparent studio renders sit inside it. */
const mediaClass = (p) => (p.isPhoto ? "media media-photo" : "media media-render");

/** The banner, header and nav every page shares (the hand-written pages carry a copy). */
export function siteHeader(current = "") {
  const links = [...CATEGORIES.map((c) => [`/c/${c.slug}`, c.label, c.slug]), ["/about", "About", "about"]];
  return `    <p class="banner"><span class="banner-tag">Demo</span> Fictional demo shop on its own origin. It knows nothing about GiftFit except one script tag. Products and photos come from the GiftFit Aurum demo catalog.</p>
    <header class="site-header">
      <a class="brand" href="/"><span class="brand-name">Lumen <i>&amp;</i> Co.</span><span class="brand-sub">Fine jewelry</span></a>
      <nav class="nav" aria-label="Shop">${links.map(([href, label, key]) => `<a href="${href}"${key === current ? ' aria-current="page"' : ""}>${label}</a>`).join("")}</nav>
    </header>`;
}

export function siteFooter() {
  return `    <footer class="site-footer">
      <div class="footer-inner">
        <div class="footer-brand">
          <p class="brand-name">Lumen <i>&amp;</i> Co.</p>
          <p>Fine jewelry in gold, silver and lab-grown stones, chosen to be given.</p>
        </div>
        <nav class="footer-links" aria-label="Footer">
          <p>Shop</p>
          ${CATEGORIES.map((c) => `<a href="/c/${c.slug}">${c.label}</a>`).join("")}
        </nav>
        <nav class="footer-links" aria-label="About">
          <p>The shop</p>
          <a href="/about">About this demo</a>
        </nav>
      </div>
      <p class="footer-note">Lumen &amp; Co. is not a real store. No orders are taken.</p>
    </footer>`;
}

function layout({ title, body, head = "", lang = "en", current = "" }) {
  return `<!doctype html>
${GENERATED}
<html lang="${lang}">
  <head>
    <meta charset="utf-8" />
    <meta name="viewport" content="width=device-width, initial-scale=1" />
    <title>${esc(title)} · Lumen &amp; Co.</title>
    <link rel="icon" href="/favicon.svg" type="image/svg+xml" />
    <link rel="stylesheet" href="/styles.css" />
${head}  </head>
  <body>
${siteHeader(current)}
    <main>
${body}
    </main>
${siteFooter()}
    <script>
      ["giftfit:sent", "giftfit:close"].forEach(function (type) {
        window.addEventListener(type, function () {
          var el = document.getElementById("events");
          if (el) el.textContent += type + " ";
        });
      });
    </script>
    <!-- The only GiftFit integration on this site: -->
    ${SNIPPET}
  </body>
</html>
`;
}

/** The catalog as the shop shows it. */
export function loadProducts(catalogPath = CATALOG_PATH) {
  const raw = JSON.parse(readFileSync(catalogPath, "utf8"));
  return raw.map((s) => {
    const a = s.attributes ?? {};
    const variants = (s.variants?.length ? s.variants : [{ metal: a.metal, price: s.price, material: a.material }]).map((v) => ({ metal: v.metal, price: v.price, material: v.material ?? String(v.metal).replace(/_/g, " ") }));
    return {
      id: s.id,
      sku: a.sku,
      slug: a.slug,
      title: s.title,
      category: s.category,
      price: s.price,
      currency: s.currency,
      image: s.images?.[0] ?? a.vto_image,
      description: a.description ?? "",
      isPhoto: a.image_source === "ai_photo",
      variants,
    };
  });
}

function swatches(p) {
  const metals = [...new Set(p.variants.map((v) => v.metal).filter((m) => METAL_LABELS[m]))];
  if (!metals.length) return "";
  return `<span class="swatches" role="img" aria-label="${esc(metals.map((m) => METAL_LABELS[m]).join(", "))}">${metals.map((m) => `<span class="swatch swatch-${m}"></span>`).join("")}</span>`;
}

function card(p) {
  return `          <a class="card" href="/p/${esc(p.slug)}"><span class="${mediaClass(p)}"><img src="${img(p.image)}" alt="" loading="lazy" /></span><span class="card-body"><span class="card-title">${esc(p.title)}</span><span class="card-meta"><span class="card-price">${money(p.price)}</span>${swatches(p)}</span></span></a>`;
}

const grid = (items) => `        <div class="grid">
${items.map(card).join("\n")}
        </div>`;

function productPage(p, products) {
  const prices = p.variants.map((v) => v.price);
  const offers =
    p.variants.length > 1
      ? { "@type": "AggregateOffer", lowPrice: Math.min(...prices).toFixed(2), highPrice: Math.max(...prices).toFixed(2), priceCurrency: p.currency, offerCount: p.variants.length, offers: [{ "@type": "Offer", price: Number(p.price).toFixed(2), priceCurrency: p.currency, availability: "https://schema.org/InStock" }] }
      : { "@type": "Offer", price: Number(p.price).toFixed(2), priceCurrency: p.currency, availability: "https://schema.org/InStock" };
  const ld = { "@context": "https://schema.org", "@type": "Product", name: p.title, sku: p.sku, image: [img(p.image)], description: p.description, brand: { "@type": "Brand", name: "Lumen & Co." }, url: `/p/${p.slug}`, offers };
  const head = `    <meta property="og:type" content="product" />
    <meta property="og:title" content="${esc(p.title)}" />
    <meta property="og:image" content="${img(p.image)}" />
    <meta property="product:price:amount" content="${Number(p.price).toFixed(2)}" />
    <meta property="product:price:currency" content="${esc(p.currency)}" />
    <script type="application/ld+json">
${JSON.stringify(ld, null, 2).replace(/</g, "\\u003c")}
    </script>
`;
  const cat = catOf(p);
  const metals =
    p.variants.length > 1
      ? `
            <div class="metals">
              <p class="label">Available in</p>
              <ul>
${p.variants.map((v) => `                <li><span class="swatch swatch-${esc(v.metal)}"></span>${esc(v.material)}<span>${money(v.price)}</span></li>`).join("\n")}
              </ul>
            </div>`
      : "";
  // Four more from the same category, starting after this one, so every page shows different neighbours.
  const same = products.filter((q) => q.category === p.category);
  const at = same.findIndex((q) => q.slug === p.slug);
  const related = [1, 2, 3, 4].map((i) => same[(at + i) % same.length]).filter((q) => q.slug !== p.slug);
  const body = `      <nav class="crumbs" aria-label="Breadcrumb"><a href="/">Home</a><a href="/c/${cat?.slug ?? ""}">${esc(cat?.label ?? "All jewelry")}</a><span aria-current="page">${esc(p.title)}</span></nav>
      <div class="pdp">
        <div class="pdp-media ${mediaClass(p)}"><img src="${img(p.image)}" alt="${esc(p.title)}" /></div>
        <div class="pdp-info">
          <p class="eyebrow">${esc(cat?.label ?? "Jewelry")}</p>
          <h1>${esc(p.title)}</h1>
          <p class="price">${money(p.price)}</p>
          <p class="pdp-desc">${esc(p.description)}</p>${metals}
          <form action="/cart/add" method="post" onsubmit="return false">
            <button type="submit" name="add">Add to cart</button>
          </form>
          <ul class="assurances">
            <li>Arrives in our signature gift box</li>
            <li>Free shipping and 30-day returns</li>
          </ul>
          <dl class="details">
            <div><dt>Material</dt><dd>${esc(p.variants.map((v) => v.material).join(" · "))}</dd></div>
            <div><dt>SKU</dt><dd>${esc(p.sku)}</dd></div>
          </dl>
          <p id="events" data-testid="host-events" aria-live="polite"></p>
        </div>
      </div>
      <section class="section">
        <div class="section-head"><h2>You may also like</h2><a class="link-arrow" href="/c/${cat?.slug ?? ""}">All ${esc(cat?.label.toLowerCase() ?? "jewelry")}</a></div>
${grid(related)}
      </section>`;
  return layout({ title: p.title, head, body, current: cat?.slug });
}

function categoryNav(products, current) {
  return `<nav class="chips" aria-label="Categories">${CATEGORIES.map((c) => `<a href="/c/${c.slug}"${c.slug === current ? ' aria-current="page"' : ""}>${c.label} <span>${products.filter((p) => p.category === c.value).length}</span></a>`).join("")}</nav>`;
}

function categoryPage(c, products) {
  const items = products.filter((p) => p.category === c.value);
  const body = `      <section class="page-head">
        <nav class="crumbs" aria-label="Breadcrumb"><a href="/">Home</a><span aria-current="page">${esc(c.label)}</span></nav>
        <h1>${esc(c.label)}</h1>
        <p>${items.length} designs. Not sure what they'd like? Ask the gift assistant in the corner.</p>
        ${categoryNav(products, c.slug)}
      </section>
      <section class="section section-tight">
${grid(items)}
      </section>
      <p id="events" data-testid="host-events" aria-live="polite"></p>`;
  return layout({ title: c.label, body, current: c.slug });
}

